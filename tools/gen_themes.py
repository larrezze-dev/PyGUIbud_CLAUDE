"""Generate ``src/pyguibud/designer/themes/sape.json`` from the SAPE brand tokens (dev tool).

It also copies the application icon ``assets/brand/logo/pyguibud.png`` next to it.

Usage: ``uv run python tools/gen_themes.py [--check]``. ``--check`` exits 1 when the committed
file differs from a fresh generation (a test does the same). The output is deterministic.

The output is derived brand data: all rights reserved, SAPE, not MIT (see NOTICE.md section 2).
Where a token fails the contrast gate of the designer (WCAG 2.2 AA, 4.5:1 for the text
ttkbootstrap paints on an accent fill), the next candidate token of the same family is used.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
TOKENS = ROOT / "assets" / "brand" / "tokens"
TARGET = ROOT / "src" / "pyguibud" / "designer" / "themes" / "sape.json"
# The application icon is copied byte for byte (same licence and fork rule as sape.json).
ICON_SOURCE = ROOT / "assets" / "brand" / "logo" / "pyguibud.png"
ICON_TARGET = TARGET.with_name("pyguibud.png")

LICENCE = "All rights reserved, SAPE. Not MIT. Generated by tools/gen_themes.py; forks must delete."
# role -> (token file, theme name, ttkbootstrap mode)
THEMES = {
    "light": ("sape.light.tokens.json", "sape-light", "light"),
    "dark": ("sape.dark.tokens.json", "sape-dark", "dark"),
    "high_contrast": ("sape.high-contrast.tokens.json", "sape-hc", "light"),
}
# Colours ttkbootstrap paints text on: candidates are tried in order, first one that passes wins.
ACCENTS = {
    "primary": ("color.action.primary.background", "color.action.primary.hover"),
    "secondary": ("color.semantic.neutral.solid", "color.semantic.neutral.hover"),
    "success": ("color.semantic.success.solid", "color.semantic.success.hover"),
    "info": ("color.semantic.info.solid", "color.semantic.info.hover"),
    "warning": ("color.semantic.warning.solid", "color.semantic.warning.hover"),
    "danger": ("color.semantic.error.solid", "color.semantic.error.hover"),
}
PLAIN = {
    "light": "color.background.subtle",
    "dark": "color.background.inverse",
    "bg": "color.background.base",
    "fg": "color.text.primary",
    "selectbg": "color.surface.selected",
    "selectfg": "color.text.primary",
    "border": "color.border.control",
    "inputfg": "color.text.primary",
    "inputbg": "color.surface.base",
    "active": "color.surface.raised",
}


def _flatten(node: dict[str, Any], prefix: str = "") -> dict[str, Any]:
    out: dict[str, Any] = {}
    for key, value in node.items():
        if key.startswith("$"):
            continue
        if isinstance(value, dict):
            if "$value" in value:
                out[prefix + key] = value["$value"]
            else:
                out.update(_flatten(value, f"{prefix}{key}."))
    return out


def _families(value: str, generic: set[str]) -> list[str]:
    return [part.strip() for part in value.split(",") if part.strip().lower() not in generic]


def _on_colour_contrast(fill: str) -> float:
    from ttkbootstrap.style.theme import _accent_on_color  # private on purpose: what is painted

    from pyguibud.designer.theme import contrast

    return contrast(_accent_on_color(fill), fill)


def build_theme(role: str, tokens_dir: Path) -> dict[str, Any]:
    """One theme object (see :mod:`pyguibud.designer.theme` for the schema)."""
    file, name, mode = THEMES[role]
    flat = _flatten(json.loads((tokens_dir / file).read_text(encoding="utf-8")))
    colours: dict[str, str] = {}
    for key, candidates in ACCENTS.items():
        for token in candidates:
            if _on_colour_contrast(flat[token]) >= 4.5:
                colours[key] = flat[token].upper()
                break
        else:
            raise SystemExit(f"{role}: no accessible token for {key} among {candidates}")
    colours.update({key: str(flat[token]).upper() for key, token in PLAIN.items()})
    order = ("primary", "secondary", "success", "info", "warning", "danger", *PLAIN)
    return {
        "name": name,
        "role": role,
        "mode": mode,
        "colors": {key: colours[key] for key in order},
        "focus": str(flat["color.border.focus"]).upper(),
        "sans": [
            flat["font.family.primary"],
            *_families(flat["font.family.system_sans"], {"sans-serif"}),
        ],
        "mono": [
            flat["font.family.mono"],
            *_families(flat["font.family.system_mono"], {"monospace"}),
        ],
    }


def build(tokens_dir: Path = TOKENS) -> str:
    """The complete, deterministic text of ``sape.json``."""
    data = {
        "_licence": LICENCE,
        "themes": [build_theme(role, tokens_dir) for role in THEMES],
    }
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the file is out of date")
    args = parser.parse_args(argv)
    outputs = {TARGET: build().encode("utf-8"), ICON_TARGET: ICON_SOURCE.read_bytes()}
    if args.check:
        stale = [p for p, data in outputs.items() if not p.exists() or p.read_bytes() != data]
        for path in stale:
            print(f"{path} is out of date; run tools/gen_themes.py", file=sys.stderr)
        return 1 if stale else 0
    for path, data in outputs.items():
        path.write_bytes(data)
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
