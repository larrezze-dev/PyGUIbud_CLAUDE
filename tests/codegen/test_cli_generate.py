def test_a_missing_output_folder_is_a_write_failure(
    capsys: pytest.CaptureFixture[str], hello: Path, tmp_path: Path
) -> None:
    code, _, err = run(capsys, str(hello), "-o", str(tmp_path / "nope" / "x.py"))
    assert code == 1 and "cannot be written" in err and "Traceback" not in err
    (tmp_path / "file.txt").write_text("x", encoding="utf-8")
    for mode in ([], ["--extract"]):  # a file used as a folder: still a write failure
        code, _, err = run(capsys, *mode, str(hello), "-o", str(tmp_path / "file.txt" / "x.py"))
        assert code == 1 and "cannot be written" in err and "Traceback" not in err


def test_a_failed_write_leaves_no_temporary_file_and_keeps_the_old_one(
    capsys: pytest.CaptureFixture[str],
    hello: Path,
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    target = tmp_path / "out.py"
    assert run(capsys, str(hello), "-o", str(target))[0] == 0
    before = target.read_bytes()

    def broken(*_args: object) -> None:
        raise OSError("disk full")

    monkeypatch.setattr(os, "replace", broken)
    code, _, err = run(capsys, str(hello), "-o", str(target))
    assert code == 1 and "cannot be written" in err
    assert target.read_bytes() == before
    assert sorted(p.name for p in tmp_path.iterdir()) == ["hello.ui", "out.py"]


