def test_output_is_independent_of_the_cli_language(
    capsys: pytest.CaptureFixture[str], hello: Path, tmp_path: Path
) -> None:
    plain, pseudo = tmp_path / "a.py", tmp_path / "b.py"
    assert run(capsys, str(hello), "-o", str(plain))[0] == 0
    code, out, _ = run(capsys, "--lang", "en_XA", str(hello), "-o", str(pseudo))
    assert code == 0 and "wrote" not in out  # the message itself is translated
    assert plain.read_bytes() == pseudo.read_bytes()
    assert run(capsys, "--lang", "de_DE", str(hello), "-o", str(pseudo))[0] == 0
    assert plain.read_bytes() == pseudo.read_bytes()


def test_o_with_two_inputs_is_a_usage_error(
    capsys: pytest.CaptureFixture[str], hello: Path, tmp_path: Path
) -> None:
    with pytest.raises(SystemExit) as info:
        main([str(hello), str(hello), "-o", str(tmp_path / "x.py")])
