from pathlib import Path

import pytest
from babel.messages.pofile import read_po

from pyguibud.codegen import GENERATED_MARKER
from pyguibud.uic import main
from tests.codegen.conftest import EXAMPLES, run_generated, write_ui

HELLO_PO = EXAMPLES / "locale" / "de_DE" / "LC_MESSAGES" / "hello.po"


def run(capsys: pytest.CaptureFixture[str], *argv: str) -> tuple[int, str, str]:
    code = main(list(argv))
    captured = capsys.readouterr()
    return code, captured.out, captured.err


@pytest.fixture
def hello(tmp_path: Path) -> Path:
    target = tmp_path / "hello.ui"
    shutil.copy(EXAMPLES / "hello.ui", target)
    return target


def _includes(tmp_path: Path) -> Path:
    write_ui(
        tmp_path / "part.ui",
        '<window id="part" kind="component"><layout type="pack"/>'
        '<widget class="Label" id="lbl"><pack/></widget></window>',
    )
    return write_ui(
        tmp_path / "host.ui",
        '<window id="main" kind="main"><layout type="pack"/>'
        '<include id="inc" src="part.ui" component="part"><pack/></include></window>',
    )


