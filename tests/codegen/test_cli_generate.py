def test_a_file_that_was_not_generated_is_replaced_only_with_force(
    capsys: pytest.CaptureFixture[str], hello: Path, tmp_path: Path
) -> None:
    app = tmp_path / "app.py"
    app.write_text("print('mine')\n", encoding="utf-8")
