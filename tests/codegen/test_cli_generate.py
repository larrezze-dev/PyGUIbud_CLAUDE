def test_extract_to_stdout_is_deterministic_and_babel_readable(
    capsys: pytest.CaptureFixture[str], monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.chdir(EXAMPLES.parent)
    code, first, err = run(capsys, "--extract", "examples/hello.ui")
    assert code == 0 and err == ""
    assert run(capsys, "--extract", "examples/hello.ui")[1] == first
    assert "POT-Creation-Date" not in first and 'msgctxt "tab"' in first
    assert "#. Title of the first tab." in first and "#: examples/hello.ui:" in first
    catalogue = read_po(io.StringIO(first))
    keys = {(m.context, m.id) for m in catalogue if m.id}
    expected = read_po(io.StringIO(HELLO_PO.read_text("utf-8")))
    wanted = {
        (m.context, m.id)
        for m in expected
        if m.id and not any("run_hello" in str(loc) for loc in m.locations)
    }
    assert keys == wanted
    assert catalogue.charset == "utf-8" and "Project-Id-Version: hello" in first
    greeting = catalogue.get("Greeting", "tab")
    assert greeting is not None and greeting.auto_comments == ["Title of the first tab."]
    assert greeting.locations[0][0] == "examples/hello.ui"


def test_extract_to_a_file_overwrites_and_is_relative_to_its_folder(
    capsys: pytest.CaptureFixture[str], hello: Path, tmp_path: Path
) -> None:
    out_dir = tmp_path / "po"
    out_dir.mkdir()
    pot = out_dir / "hello.pot"
    pot.write_text("old", encoding="utf-8")
    code, out, err = run(capsys, "--extract", str(hello), "-o", str(pot))
    assert code == 1 and "was not generated by pyguibud-uic" in err  # QA-11-01
    assert pot.read_text(encoding="utf-8") == "old"
    code, out, err = run(capsys, "--extract", str(hello), "-o", str(pot), "--force")
    assert code == 0 and out == f"wrote {pot}\n" and err == ""
    assert run(capsys, "--extract", str(hello), "-o", str(pot))[0] == 0  # its own template
    text = pot.read_bytes().decode("utf-8")
    assert "\r" not in text and "#: ../hello.ui:" in text
    assert text.startswith("# Translations template for hello.\n")


def test_extract_merges_inputs_and_writes_nothing_when_one_fails(
    capsys: pytest.CaptureFixture[str], hello: Path, tmp_path: Path
) -> None:
    other = write_ui(
        tmp_path / "other.ui",
        '<window id="main" kind="main"><prop name="title" translatable="true" '
        'context="window title">Hello PyGUIbud</prop><layout type="pack"/></window>',
    )
    code, merged, _ = run(capsys, "--extract", str(hello), str(other))
    assert code == 0 and merged.count('msgid "Hello PyGUIbud"') == 1
    broken = tmp_path / "broken.ui"
    broken.write_text("<x", encoding="utf-8")
    pot = tmp_path / "x.pot"
    code, out, err = run(capsys, "--extract", str(hello), str(broken), "-o", str(pot))
    assert code == 1 and out == "" and "error" in err and not pot.exists()


def test_extract_escapes_comments_and_multi_line_texts(
    capsys: pytest.CaptureFixture[str], tmp_path: Path
) -> None:
    ui = write_ui(
        tmp_path / "e.ui",
        '<window id="main" kind="main"><prop name="title" translatable="true" '
        'comment="one&#10;two">Line1&#10;Say &quot;hi&quot;\\ tab&#9;end</prop>'
        '<layout type="pack"/></window>',
    )
    code, out, _ = run(capsys, "--extract", str(ui))
    assert code == 0
    assert "#. one\n#. two\n" in out
    messages = [m for m in read_po(io.StringIO(out)) if m.id]
    assert [m.id for m in messages] == ['Line1\nSay "hi"\\ tab\tend']
    assert 'msgid ""\n"Line1\\n"\n"Say \\"hi\\"\\\\ tab\\tend"' in out
