"""Spec packaging D6: one version literal, mirrored by the pins, the runtime and hello_ui.py."""

from __future__ import annotations

import importlib.util
import re
import shutil
import subprocess
import sys
from pathlib import Path
from types import ModuleType
from typing import Any

import pytest

import pyguibud_runtime
from pyguibud.__about__ import __version__
from tests._paths import ROOT, RUNTIME_SRC


def _bump_tool() -> ModuleType:
    spec = importlib.util.spec_from_file_location(
        "bump_version", ROOT / "tools" / "bump_version.py"
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _literal() -> str:
    text = (RUNTIME_SRC / "pyguibud" / "__about__.py").read_text(encoding="utf-8")
    found = re.findall(r'^__version__ = "([^"]*)"$', text, re.MULTILINE)
    assert len(found) == 1
    return str(found[0])


def test_the_literal_is_the_imported_version_and_a_public_pep440_one() -> None:
    assert _literal() == __version__ == pyguibud_runtime.__version__
    assert _bump_tool().VERSION.fullmatch(__version__)


def _toml(*parts: str) -> str:
    return ROOT.joinpath(*parts).read_text(encoding="utf-8")  # no tomllib on Python 3.10


def test_the_root_project_pins_the_runtime_to_the_same_version() -> None:
    pins = re.findall(r'"pyguibud-runtime(?:\[pyside\])?==([^"]*)"', _toml("pyproject.toml"))
    assert pins == [__version__, __version__]
    assert f'pyside = ["pyguibud-runtime[pyside]=={__version__}"]' in _toml("pyproject.toml")


def test_both_projects_read_the_one_literal() -> None:
    assert 'path = "runtime/src/pyguibud/__about__.py"' in _toml("pyproject.toml")
    assert 'path = "src/pyguibud/__about__.py"' in _toml("runtime", "pyproject.toml")
    for text in (_toml("pyproject.toml"), _toml("runtime", "pyproject.toml")):
        assert 'dynamic = ["version"]' in text


def test_the_generated_example_names_the_version() -> None:
    first = (ROOT / "examples" / "hello_ui.py").read_text(encoding="utf-8").splitlines()[0]
    assert first.startswith(f"# Generated by pyguibud-uic {__version__} (format ")


def test_bump_version_rewrites_every_site(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    tool = _bump_tool()
    about, pyproject = tmp_path / "__about__.py", tmp_path / "pyproject.toml"
    shutil.copyfile(RUNTIME_SRC / "pyguibud" / "__about__.py", about)
    shutil.copyfile(ROOT / "pyproject.toml", pyproject)
    calls: list[list[str]] = []

    def fake_run(argv: list[str], **_kwargs: Any) -> None:
        calls.append(argv)

    monkeypatch.setattr(tool, "ABOUT", about)
    monkeypatch.setattr(tool, "PYPROJECT", pyproject)
    monkeypatch.setattr(subprocess, "run", fake_run)
    assert tool.main(["9.8.7rc6"]) == 0
    assert '__version__ = "9.8.7rc6"' in about.read_text(encoding="utf-8")
    text = pyproject.read_text(encoding="utf-8")
    assert text.count("==9.8.7rc6") == 2 and f"=={__version__}" not in text
    assert calls[0][:2] == [sys.executable, "-c"] and calls[1] == ["uv", "lock"]


@pytest.mark.parametrize("version", ["1.0", "v1.0.0", "1.0.0+local", "1!1.0.0", "1.0.0-rc1", ""])
def test_bump_version_refuses_a_non_public_version(version: str) -> None:
    with pytest.raises(SystemExit) as caught:
        _bump_tool().main([version])
    assert caught.value.code == 2
