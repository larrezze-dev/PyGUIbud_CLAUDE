"""``pyguibud.codegen``: Python code from ``.ui`` files (spec ``docs/specs/codegen.md``, ADR-008).

The generated module needs only the standard library and ``ttkbootstrap``. This package never
imports a toolkit, ``pyguibud_runtime`` or its own ``_support`` module: it copies the *text* of
``_support.py``. The output depends only on the ``.ui`` files (and their images), never on the
CLI language, the machine, the working directory, the hash seed or the time.
"""

from __future__ import annotations

import keyword
import os
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Final

from pyguibud.__about__ import __version__
from pyguibud.codegen._emit import Emitter, image_constant, lit
from pyguibud.codegen._errors import (
    M_INVALID_ONE,
    M_NOTHING,
    M_OUTSIDE,
    M_READ_ONLY,
    M_UNSAFE,
    CodegenError,
)
from pyguibud.codegen._plan import Plan
from pyguibud.codegen._pot import extract_pot
from pyguibud.core.diagnostics import Finding
from pyguibud.core.files import DiskFiles
from pyguibud.core.registry import default_registry
from pyguibud.core.validate import validate
from pyguibud.core.xml_io import ReadResult

__all__ = [
    "FORMAT",
    "GENERATED_MARKER",
    "CodegenError",
    "GeneratedModule",
    "default_output",
    "extract_pot",
    "generate_python",
    "support_text",
]

GENERATED_MARKER: Final = "# Generated by pyguibud-uic"
FORMAT: Final = 1

_SUPPORT_FILE: Final = Path(__file__).with_name("_support.py")
_BEGIN: Final = "# --- BEGIN SUPPORT ---"
_END: Final = "# --- END SUPPORT ---"
_NOT_NAME: Final = re.compile(r"[^A-Za-z0-9_]")
# Warnings for --check and load_ui, refused by the code generator unless allowed (QA-11-03).
_OUTSIDE_CODES: Final = frozenset({"validate.absolute_path", "validate.path_escapes"})


@dataclass(frozen=True)
class GeneratedModule:
    """The text of a generated module (LF newlines, ends with one newline)."""

    text: str
    class_name: str
    warnings: tuple[Finding, ...]
    #: Every .ui file the module was generated from (the input and its included files).
    sources: tuple[str, ...] = ()


def support_text() -> str:
    """The support region of ``_support.py``, without its markers (CRLF-safe)."""
    text = _SUPPORT_FILE.read_bytes().decode("utf-8").replace("\r\n", "\n")
    lines = text.split("\n")
    region = lines[lines.index(_BEGIN) + 1 : lines.index(_END)]
    return "\n".join(region).strip("\n")


def _stem_name(path: str) -> str:
    stem = _NOT_NAME.sub("_", os.path.splitext(os.path.basename(path))[0])
    return "_" + stem if stem[:1].isdigit() else stem


def default_output(path: str) -> str:
    """``"dir/my-form.ui"`` -> ``"dir/my_form_ui.py"`` (an importable module name)."""
    return os.path.join(os.path.dirname(path), _stem_name(path) + "_ui.py")


def _class_name(main_id: str | None, path: str) -> str:
    if main_id:
        base = main_id[:1].upper() + main_id[1:]
    else:
        # A stem without ASCII letters or digits ("日本.ui", "__.ui") gives a fixed name.
        stem = _stem_name(path)
        base = stem if stem.strip("_") else "Form"
    name = "Ui_" + base
    if not name.isascii() or not name.isidentifier() or keyword.iskeyword(name):
        raise CodegenError("codegen.unsafe_name", M_UNSAFE, name=name)
    return name


def generate_python(
    result: ReadResult, path: str, *, output: str, allow_outside: bool = False
) -> GeneratedModule:
    """Validate ``result`` (read from ``path``) with its includes and images, then generate.

    ``output`` is the path the module will be written to; it is used only to compute the
    relative catalogue folders and never appears in the text. An image or include path that is
    absolute or leaves the folder of its ``.ui`` file is only a warning for ``--check`` and
    ``load_ui``, but the code generator refuses it unless ``allow_outside`` (``--force``).

    Raises:
        CodegenError: ``codegen.invalid_document``, ``codegen.read_only``,
            ``codegen.outside_path``, ``codegen.nothing_to_generate``,
            ``codegen.unsafe_name`` or ``codegen.image_changed``.
    """
    registry = default_registry()
    files = DiskFiles(path, result)
    report = validate(
        result.document,
        registry,
        source=result.source,
        positions=result.positions,
        files=files,
    )
    errors = report.errors
    if errors:
        raise CodegenError(
            "codegen.invalid_document", M_INVALID_ONE, findings=errors, path=path, count=len(errors)
        )
    if result.read_only:
        raise CodegenError(
            "codegen.read_only", M_READ_ONLY, path=path, version=result.source_version
        )
    outside = tuple(f for f in report.warnings if f.code in _OUTSIDE_CODES)
    if outside and not allow_outside:  # QA-11-03: the module would embed files from elsewhere
        raise CodegenError(
            "codegen.outside_path",
            M_OUTSIDE,
            findings=outside,
            path=path,
            src=outside[0].params.get("path", ""),
            force="--force",
        )
    document = result.document
    mains = [w for w in document.children if w.kind == "main"]
    windows = mains + [w for w in document.children if w.kind == "dialog"]
    if not windows:
        raise CodegenError("codegen.nothing_to_generate", M_NOTHING, path=path)
    class_name = _class_name(mains[0].id if mains else None, path)
    plan = Plan(files, document, result.source, output)
    emitter = Emitter(plan, registry)
    build = emitter.build(windows)
    docs = tuple(
        (
            doc.document.meta.i18n_domain,
            doc.document.meta.source_locale,
            plan.locale_dir(doc, output),
        )
        for doc in plan.docs
    )
    lines = [
        f"{GENERATED_MARKER} {__version__} (format {FORMAT}) from "
        f"{os.path.basename(path)!a}. Do not edit: changes are lost on regeneration.",
        "# Requires Python >= 3.10 and ttkbootstrap >= 2.2, < 3. This module does not import "
        "PyGUIbud.",
        "from __future__ import annotations",
        "",
        f"# --- support: identical in every generated module (pyguibud-uic format {FORMAT}) ---",
        support_text(),
        "# --- end of support ---",
        "",
        f"_DOCS = {lit(docs)}",
        f"_HANDLERS = {lit(tuple(sorted(emitter.handlers)))}",
        f"_THEME = {lit(document.meta.theme)}",
    ]
    for image in plan.images:
        lines += image_constant(image.number, image.data)
    lines += [
        "",
        "",
        f"class {class_name}(_Ui):",
        '    """Generated interface; build it with setup_ui()."""',
        "",
        "    _docs = _DOCS",
        "    _handler_names = _HANDLERS",
        "    _theme_name = _THEME",
        *([] if mains else ["    _has_main = False"]),
        "",
        *build,
    ]
    for number in sorted(emitter.methods):
        lines += ["", *emitter.methods[number]]
    lines += ["", "", 'if __name__ == "__main__":', f"    _preview({class_name})"]
    return GeneratedModule(
        text="\n".join(lines) + "\n",
        class_name=class_name,
        warnings=(*report.warnings, *plan.warnings),
        sources=tuple(files.path_of(doc.key) for doc in plan.docs),
    )
