class CodegenError(PyGUIbudError):
    """Code cannot be generated from a document; ``code`` is one of ``codegen.*``.

    ``findings`` holds the validator errors for ``codegen.invalid_document``.
    """

    def __init__(
        self, code: str, message: str, /, *, findings: tuple[Finding, ...] = (), **params: object
    ) -> None:
        super().__init__(code, message, **params)
        self.findings = findings
